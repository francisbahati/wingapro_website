// scripts/generate-firebase-config.js
// Runs before `next dev` and `next build` to generate public/firebase-config.js
// from environment variables. This keeps the service worker config in sync
// with NEXT_PUBLIC_FIREBASE_* vars without hardcoding any values.
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

// ---- Minimal .env file loader (no dependencies) ----
function loadEnvFile(fileName) {
  const filePath = path.join(ROOT, fileName);
  if (!fs.existsSync(filePath)) return;

  const content = fs.readFileSync(filePath, 'utf8');
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const eq = line.indexOf('=');
    if (eq === -1) continue;

    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();

    // strip optional surrounding quotes
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    if (!process.env[key]) process.env[key] = value;
  }
}

loadEnvFile('.env.local');
loadEnvFile('.env');

// ---- Required NEXT_PUBLIC_FIREBASE_* values ----
const REQUIRED_KEYS = [
  'NEXT_PUBLIC_FIREBASE_API_KEY',
  'NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN',
  'NEXT_PUBLIC_FIREBASE_PROJECT_ID',
  'NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET',
  'NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID',
  'NEXT_PUBLIC_FIREBASE_APP_ID',
];

const missing = REQUIRED_KEYS.filter((k) => !process.env[k]);
if (missing.length > 0) {
  console.warn('⚠️  Missing NEXT_PUBLIC_FIREBASE_* env vars:');
  for (const k of missing) console.warn(`    • ${k}`);
  console.warn('    Firebase background messaging will be disabled until fixed.');
}

const config = {
  apiKey:            process.env.NEXT_PUBLIC_FIREBASE_API_KEY             || '',
  authDomain:        process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN         || '',
  projectId:         process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID          || '',
  storageBucket:     process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET      || '',
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || '',
  appId:             process.env.NEXT_PUBLIC_FIREBASE_APP_ID              || '',
  measurementId:     process.env.NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID      || '',
};

const output = `// AUTO-GENERATED by scripts/generate-firebase-config.js — DO NOT EDIT.
// Generated at: ${new Date().toISOString()}
// Source: NEXT_PUBLIC_FIREBASE_* environment variables
self.FIREBASE_CONFIG = ${JSON.stringify(config, null, 2)};
`;

const targetDir = path.join(ROOT, 'public');
if (!fs.existsSync(targetDir)) fs.mkdirSync(targetDir, { recursive: true });

const targetFile = path.join(targetDir, 'firebase-config.js');
fs.writeFileSync(targetFile, output);

console.log(`✅ Wrote ${path.relative(ROOT, targetFile)}`);